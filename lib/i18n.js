export function detectLocale(navLang, stored) {
  if (stored === 'es' || stored === 'en') return stored;
  const lang = String(navLang || '').toLowerCase();
  if (lang.startsWith('en')) return 'en';
  return 'es';
}

export function t(locale, key, vars) {
  const table = DICT[locale] || DICT.es;
  let text = table[key] ?? DICT.es[key] ?? key;
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.replaceAll(`{${name}}`, String(value));
    }
  }
  return text;
}

export function translateError(locale, message) {
  const text = String(message || '');
  if (!text || locale !== 'en') return text;
  if (ERROR_EN[text]) return ERROR_EN[text];
  for (const [prefix, replacement] of ERROR_PREFIX) {
    if (text.startsWith(prefix)) return replacement + text.slice(prefix.length);
  }
  return text;
}

export function dictKeys(locale) {
  return Object.keys(DICT[locale] || {}).sort();
}
